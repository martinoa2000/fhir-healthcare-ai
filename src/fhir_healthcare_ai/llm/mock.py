# -- prompt parsing -------------------------------------------------------------------

_QUESTION = re.compile(r"^Question:\s*(.+?)\s*$", re.MULTILINE)
_TODAY = re.compile(r"Today's date is (\d{4}-\d{2}-\d{2})")
_PATIENT_ID = re.compile(r"\b(?:patient(?:\s+id)?[:\s]+)([A-Za-z0-9\-.]{1,64})", re.IGNORECASE)


def _extract_question(text: str) -> str:
    match = _QUESTION.search(text)
    return match.group(1).strip() if match else text.strip()


def _extract_today(text: str) -> datetime | None:
    match = _TODAY.search(text)
    if not match:
        return None
    return datetime.fromisoformat(match.group(1)).replace(tzinfo=UTC)


def _extract_patient_id(question: str) -> str | None:
    match = _PATIENT_ID.search(question)
    return match.group(1) if match else None


def _is_narrative_request(messages: Sequence[LLMMessage]) -> bool:
    return any("You summarise the results" in m.content for m in messages if m.role == "system")


def _narrative(user_text: str) -> str:
    """A factual restatement. It adds no number that was not handed to it."""
    question = _extract_question(user_text)
    count_match = re.search(r"Patients matched:\s*(\d+)", user_text)
    count = count_match.group(1) if count_match else "an unreported number of"
    return (
        f"The query for {question.rstrip('?').lower()} matched {count} patients in the "
        "synthetic dataset. Supporting resources are listed as evidence alongside each "
        "patient. These results are retrieval output for review, not a clinical assessment."
    )
