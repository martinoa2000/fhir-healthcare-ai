@dataclass(frozen=True)
class Rule:
    """One recognised question shape.

    Args:
        name: Identifier, surfaced in logs so a benchmark failure can be traced to the
            rule that fired.
        keywords: Every group must have at least one member present in the question.
            Nested tuples are OR, the outer tuple is AND.
        build: Produces the plan dict for a question that matched.
    """

    name: str
    keywords: tuple[tuple[str, ...], ...]
    build: Callable[[str, datetime], dict[str, Any]]

    def matches(self, question: str) -> bool:
        return all(any(word in question for word in group) for group in self.keywords)


class MockLLMProvider(LLMProvider):
    """Rule-based stand-in for a real model."""

    name = "mock"

    def __init__(self, *, today: datetime | None = None) -> None:
        self._today = today

    async def complete(
        self,
        messages: list[LLMMessage],
        *,
        temperature: float | None = None,
        max_tokens: int | None = None,
        json_mode: bool = False,
    ) -> LLMResponse:
        del temperature, max_tokens, json_mode
        user_text = "\n".join(m.content for m in messages if m.role == "user")

        if _is_narrative_request(messages):
            payload: Any = _narrative(user_text)
            text = str(payload)
        else:
            question = _extract_question(user_text)
            today = self._today or _extract_today(user_text) or datetime.now(UTC)
            plan = plan_for(question, today)
            logger.debug("mock planner produced a plan", extra={"question": question})
            text = json.dumps(plan, indent=2)

        return LLMResponse(
            text=text,
            model=MODEL_NAME,
            prompt_tokens=sum(len(m.content) // 4 for m in messages),
            completion_tokens=len(text) // 4,
            finish_reason="stop",
        )


def plan_for(question: str, today: datetime) -> dict[str, Any]:
    """The planner itself, exposed directly so tests need no provider plumbing."""
    lowered = question.lower()
    for rule in RULES:
        if rule.matches(lowered):
            plan = rule.build(question, today)
            plan.setdefault("assumptions", [])
            plan["assumptions"].append(f"Plan generated by the {rule.name} rule ({MODEL_NAME}).")
            return plan
    return _unsupported(question)


