def _date(today: datetime, days_ago: int) -> str:
    return (today - timedelta(days=days_ago)).date().isoformat()


def _token(name: str, values: Sequence[str], system: str) -> dict[str, Any]:
    return {"name": name, "values": list(values), "system": system}


